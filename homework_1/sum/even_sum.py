"""
Объяснение
Сначала находим сумму всех чисел. Если сумма четная, возвращаем ее.
Если сумма нечетная, находим минимальное нечетное число и убираем его
из суммы. Нечетное минус нечетное дает четное, а удаление минимального
числа позволяет сохранить максимально возможную сумму

оценка сложности
O(n) по времени, потому что сначала складываем числа, а затем при необходимости
просматриваем массив для поиска минимального нечетного числа
O(1) дополнительной памяти, потому что храним только сумму и одно число

Визуализация работы алгоритма
Пример для массива [5, 7, 13, 2, 14]:
1. Общая сумма: 5 + 7 + 13 + 2 + 14 = 41
2. Сумма 41 нечетная, поэтому ищем минимальное нечетное число
3. Нечетные числа: 5, 7, 13. Минимальное из них — 5
4. Вычитаем его из суммы: 41 - 5 = 36
Ответ: 36
"""


def max_even_sum(numbers):
    total = sum(numbers)

    if total % 2 == 0:
        return total

    minimum_odd = total

    for number in numbers:
        if number % 2 != 0 and number < minimum_odd:
            minimum_odd = number

    return total - minimum_odd


if __name__ == "__main__":
    numbers = list(map(int, input().split()))
    print(max_even_sum(numbers))
