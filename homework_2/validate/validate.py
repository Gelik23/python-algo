"""
Объяснение
Создаем пустой стек и переменную popped_index. Она показывает, какой элемент
из popped нам нужно удалить следующим.

По очереди берем числа из pushed и добавляем их в стек. После каждого добавления
смотрим на вершину. Если она равна нужному элементу из popped, удаляем ее и
увеличиваем popped_index. Проверку делаем в цикле while, потому что иногда после
одного push можно сделать несколько pop подряд.

Если нужное число лежит не на вершине, достать его пока нельзя, поэтому продолжаем
добавлять числа. В конце проверяем стек: если он пустой, все элементы получилось
удалить в заданном порядке и возвращаем True. Если в стеке что-то осталось,
такой порядок получить нельзя и возвращаем False.

Сложность
O(n) по времени: каждое число один раз добавляем в стек и не больше одного раза
удаляем. Хотя внутри for есть while, всего операций pop все равно не больше n.
O(n) по памяти: в худшем случае сначала придется положить в стек все числа.

Визуализация работы алгоритма
pushed = [2, 5, 1, 4, 3, 6]
popped = [1, 3, 4, 5, 6, 2]

действие | стек после действия | что проверяем в popped
push(2)  | [2]                 | нужен 1, вершина 2 — не удаляем
push(5)  | [2, 5]              | нужен 1, вершина 5 — не удаляем
push(1)  | [2, 5, 1]           | pop(1) -> стек [2, 5], теперь нужен 3
push(4)  | [2, 5, 4]           | нужен 3, вершина 4 — не удаляем
push(3)  | [2, 5, 4, 3]        | pop(3), pop(4), pop(5) -> стек [2]
push(6)  | [2, 6]              | pop(6), pop(2) -> стек []

В конце стек пустой, поэтому функция возвращает True. В этом примере некоторые
числа ждут в стеке, а после push(3) и push(6) выполняется несколько pop подряд.
"""


def validate_stack_sequences(pushed, popped):
    stack = []
    popped_index = 0

    for number in pushed:
        stack.append(number)

        while stack and stack[-1] == popped[popped_index]:
            stack.pop()
            popped_index += 1

    return len(stack) == 0


if __name__ == "__main__":
    pushed = list(map(int, input().split()))
    popped = list(map(int, input().split()))
    print(validate_stack_sequences(pushed, popped))
