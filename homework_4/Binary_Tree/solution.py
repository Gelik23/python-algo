"""
ДЗ 4. Бинарные деревья поиска

Задача 1. Вставка в BST и обходы дерева
--------------------------------------
Идея решения
У каждого узла есть значение и две ссылки: на левого и правого потомка.
Если потомка нет, в соответствующей ссылке хранится None. Класс Node
описывает один узел, а BST хранит ссылку root на корень всего дерева.

В дереве поиска все числа слева от узла должны быть меньше его значения,
а все числа справа — больше. Это правило относится ко всему поддереву,
а не только к двум ближайшим детям.

Чтобы вставить число, начинаем с корня. Если число меньше текущего,
идём влево, если больше — вправо. Повторяем сравнения, пока не найдём
пустое место. Там и создаём новый узел. Так мы учитываем ограничения
всех узлов, через которые прошли, и сохраняем свойство дерева поиска.
Если такое число уже есть, повторно его не добавляем.

В коде insert запускает вставку, а _insert выполняет рекурсивный спуск.
Каждый вызов _insert возвращает корень своего поддерева. Поэтому результат
сохраняется в node.left или node.right: иначе новый узел не присоединится
к дереву. Сам метод insert изменяет дерево и ничего не возвращает.

Для обхода нужно посетить все узлы и собрать значения в список.
Разница между обходами — в том, когда добавлять текущий узел:

preorder         — узел, левое поддерево, правое поддерево;
inorder          — левое поддерево, узел, правое поддерево;
postorder        — левое поддерево, правое поддерево, узел;
reverse_preorder — узел, правое поддерево, левое поддерево;
reverse_inorder  — правое поддерево, узел, левое поддерево;
reverse_postorder— правое поддерево, левое поддерево, узел.

В reverse-обходах меняем местами обход левого и правого поддеревьев.
Просто развернуть готовый список обычного обхода — другое действие.

В каждой функции создаём result. Вложенная функция visit обходит дерево
и добавляет в этот список значения через append. Если visit получает
None, она сразу заканчивает работу: в этой ветке больше нет узлов.
Так обрабатывается каждое поддерево, и каждый узел попадает в ответ
ровно один раз. Обходы работают и для дерева, которое не является BST.

Визуализация на примере с отрицательными числами, повторами и изгибами веток
Вставляем числа в таком порядке:
[0, -12, 15, -20, -4, 9, 23, -8, -1, 11, 18, -6, 10, -8, 0]

В схеме L означает левого потомка, R — правого:

0
├── L: -12
│   ├── L: -20
│   └── R: -4
│       ├── L: -8
│       │   └── R: -6
│       └── R: -1
└── R: 15
    ├── L: 9
    │   └── R: 11
    │       └── L: 10
    └── R: 23
        └── L: 18

Дерево получилось несимметричным. Есть узлы только с одним ребёнком,
а направление спуска несколько раз меняется. Например, вставка 10:

Шаг | Текущий узел | Сравнение | Действие
1   | 0            | 10 > 0    | идём вправо
2   | 15           | 10 < 15   | идём влево
3   | 9            | 10 > 9    | идём вправо
4   | 11           | 10 < 11   | идём влево
5   | None         | —         | создаём Node(10)

Повторная вставка -8 проходит путь 0 -> -12 -> -4 -> -8.
На последнем шаге значения равны, поэтому дерево не меняется.
Повторная вставка 0 заканчивается сразу у корня. В итоге узлов 13,
хотя попыток вставки было 15.

Разберём inorder по шагам. В таблице показан именно момент добавления
значения, а не каждый технический вызов рекурсии:

Шаг | Добавляем | Почему сейчас
1   | -20       | спустились в самый левый узел
2   | -12       | его левое поддерево уже пройдено
3   | -8        | в правой ветке -12 сначала дошли влево от -4
4   | -6        | это правый потомок -8, левого у него нет
5   | -4        | всё его левое поддерево пройдено
6   | -1        | обходим правого потомка -4
7   | 0         | вся левая часть исходного дерева готова
8   | 9         | в правой части сначала идём влево от 15
9   | 10        | у 9 идём вправо к 11, затем влево к 10
10  | 11        | его левый потомок уже обработан
11  | 15        | закончили его левое поддерево
12  | 18        | в ветке 23 сначала посещаем левого потомка
13  | 23        | заканчиваем правую часть дерева

Для остальных обходов меняется порядок этих действий.
Полные последовательности посещения (слева направо, по одному шагу):

preorder:
[0, -12, -20, -4, -8, -6, -1, 15, 9, 11, 10, 23, 18]
inorder:
[-20, -12, -8, -6, -4, -1, 0, 9, 10, 11, 15, 18, 23]
postorder:
[-20, -6, -8, -1, -4, -12, 10, 11, 9, 18, 23, 15, 0]
reverse_preorder:
[0, 15, 23, 18, 9, 11, 10, -12, -4, -1, -8, -6, -20]
reverse_inorder:
[23, 18, 15, 11, 10, 9, 0, -1, -4, -6, -8, -12, -20]
reverse_postorder:
[18, 23, 10, 11, 9, 15, -1, -6, -8, -4, -20, -12, 0]

Сложность
Пусть n — число узлов, h — высота дерева в узлах.
Одна вставка занимает O(h) времени: идём только по одной ветке.
На этом пути одновременно остаётся до h рекурсивных вызовов,
поэтому дополнительная память тоже O(h).
Если дерево сбалансировано, h = O(log n). Если оно вытянулось в цепочку,
h = O(n). Автоматической балансировки в этой реализации нет.
Построение дерева из n чисел в худшем случае занимает O(n²):
при вставке по возрастанию пути становятся всё длиннее.
Если высота на каждом шаге остаётся логарифмической, получаем O(n log n).

Любой из шести обходов занимает O(n) времени: посещаем каждый узел
один раз, добавление в список через append в среднем занимает O(1).
Для списка ответа нужна память O(n), для рекурсии — O(h).
Вместе получаем O(n + h). Само дерево занимает O(n) памяти.


Задача 2. Проверка BST
----------------------
Идея решения
На вход приходит корень уже существующего дерева. Нельзя предполагать,
что его построили правильной вставкой. Нужно проверить все ограничения
и вернуть True, если нарушений нет, иначе False.

Сравнить каждый узел только с его детьми недостаточно. Число может быть
меньше своего родителя, но при этом оказаться не с той стороны от корня.
Поэтому при спуске запоминаем диапазон, в котором должно лежать значение.

У корня ограничений нет. Когда идём влево, значение текущего узла
становится верхней границей. Когда идём вправо — нижней.
Вторую границу сохраняем, потому что ограничение от предка всё ещё действует.
В коде эти границы называются lower и upper. None означает, что с этой
стороны ограничения пока нет. Сами границы в допустимый диапазон не входят:
одинаковые значения в нашем BST запрещены.

Если узел нарушает хотя бы одну границу, сразу возвращаем False.
Иначе проверяем оба поддерева. Пустая ветка возвращает True:
в ней нет значений, которые могли бы нарушить правило.
Так каждый узел проверяется с учётом всех его предков. Если все проверки
прошли, дерево удовлетворяет определению BST.

Визуализация: ошибка, которую не видно при сравнении соседей
Это дерево создаём вручную через Node, а не через BST.insert:

0
├── L: -10
└── R: 20
    ├── L: 10
    │   ├── L: 5
    │   │   └── L: -1  <-- ошибка
    │   └── R: 15
    └── R: 30

Каждая отдельная связь выглядит правильно: -10 < 0, 20 > 0,
10 < 20, 5 < 10, -1 < 5, 15 > 10, 30 > 20.
Но -1 находится в правом поддереве 0, где все значения должны быть больше 0.
Между ошибочным узлом и корнем четыре ребра.

Шаг | Узел | Что разрешено       | Что происходит
1   | 0    | любое число         | подходит, начинаем левую ветку
2   | -10  | меньше 0            | подходит, оба потомка пустые
3   | 20   | больше 0            | подходит, идём влево
4   | 10   | больше 0, меньше 20 | подходит, идём влево
5   | 5    | больше 0, меньше 10 | подходит, идём влево
6   | -1   | больше 0, меньше 5  | нарушение нижней границы

Обрати внимание: верхняя граница менялась 20 -> 10 -> 5,
а нижняя всё это время оставалась равна 0. Именно она обнаружила ошибку.
False возвращается от -1 к 5, затем к 10, 20 и 0.
Ветки 15 и 30 уже не рассматриваются: одного нарушения достаточно.
Если заменить -1 на 1, это дерево станет корректным BST.

Сложность
В худшем случае время O(n): например, у правильного дерева нужно
проверить все узлы. На каждом шаге делаем постоянное число сравнений.
Дополнительная память O(h): храним рекурсивные вызовы по текущему пути.
Это O(log n) для сбалансированного дерева и O(n) для цепочки.


Задача 3. Проверка сбалансированности
------------------------------------
Идея решения
Дерево сбалансировано, если в каждом узле высоты левого и правого
поддеревьев отличаются не больше чем на 1. Количество узлов слева
и справа само по себе ответа не даёт. Здесь важна длина самой глубокой
ветки, причём проверять нужно каждый узел, а не только корень.

Высоту считаем в узлах: у пустой ветки она 0, у листа — 1.
Чтобы узнать высоту родителя, сначала узнаём высоты его детей,
берём большую и прибавляем 1 за самого родителя.

Не будем заново обходить одно поддерево для каждого его предка.
Вместо этого функция height за один проход получает высоты снизу вверх
и сразу сравнивает их. Если разница больше 1, возвращаем -1.
Это сигнал об ошибке: настоящая высота отрицательной быть не может.
Если один из детей уже вернул -1, передаём этот сигнал дальше,
потому что всё дерево со сломанным балансом внутри тоже несбалансировано.

Почему проверка работает: у пустых веток баланс не нарушен. Для каждого
следующего узла проверяем оба поддерева и разницу их высот. Поэтому
возвращённая неотрицательная высота означает, что внутри всё проверено.
Остаётся посмотреть на результат у корня: -1 означает False,
любая настоящая высота — True. Значения узлов на баланс не влияют,
поэтому проверка работает и для бинарного дерева, которое не является BST.

Визуализация: корень выглядит нормально, но нарушение спрятано справа

10
├── L: 4
│   ├── L: 2
│   │   ├── L: 1
│   │   └── R: 3
│   └── R: 6
│       └── R: 7
└── R: 20
    ├── L: 15
    └── R: 25
        └── R: 30
            └── R: 35

У корня 10 настоящая высота левого поддерева равна 3, правого — 4.
Разница всего 1. Более того, слева узлов 6, а справа 5:
сторона с меньшим количеством узлов оказалась выше.
По одной проверке корня дерево можно было бы ошибочно признать сбалансированным.

Проследим вычисления в том порядке, в котором их делает height:

Шаг | Узел | Слева | Справа | Что возвращает
1   | 1    | 0     | 0      | 1
2   | 3    | 0     | 0      | 1
3   | 2    | 1     | 1      | 2
4   | 7    | 0     | 0      | 1
5   | 6    | 0     | 1      | 2
6   | 4    | 2     | 2      | 3
7   | 15   | 0     | 0      | 1
8   | 35   | 0     | 0      | 1
9   | 30   | 0     | 1      | 2
10  | 25   | 0     | 2      | -1: разница высот равна 2
11  | 20   | 1     | -1     | -1: справа уже найдено нарушение
12  | 10   | 3     | -1     | -1: правое поддерево несбалансировано

Первую ошибку находим в узле 25. Значение -1 затем доходит до корня,
и is_balanced возвращает False. Хотя у 10 разница настоящих высот
допустимая, внутри правого поддерева правило нарушено.

Если убрать лист 35, у 30 высота станет 1, у 25 — 2, у 20 — 3.
Тогда у каждого узла разница высот будет не больше 1,
а у корня высоты станут равны 3 и 3. Проверка вернёт True.

Сложность
Время O(n) в худшем случае: каждый узел обрабатываем не больше одного раза,
а высоты поддеревьев используем уже готовые, без повторных обходов.
Дополнительная память O(h) нужна для рекурсии: O(log n)
в сбалансированном дереве и O(n) в цепочке.
"""


class Node:
    def __init__(self, value):
        self.value = value
        self.left = None
        self.right = None


class BST:
    def __init__(self):
        self.root = None

    def insert(self, value):
        self.root = self._insert(self.root, value)

    def _insert(self, node, value):
        if node is None:
            return Node(value)
        if value < node.value:
            node.left = self._insert(node.left, value)
        elif value > node.value:
            node.right = self._insert(node.right, value)
        return node


def preorder(root):
    result = []

    def visit(node):
        if node is None:
            return
        result.append(node.value)
        visit(node.left)
        visit(node.right)

    visit(root)
    return result


def inorder(root):
    result = []

    def visit(node):
        if node is None:
            return
        visit(node.left)
        result.append(node.value)
        visit(node.right)

    visit(root)
    return result


def postorder(root):
    result = []

    def visit(node):
        if node is None:
            return
        visit(node.left)
        visit(node.right)
        result.append(node.value)

    visit(root)
    return result


def reverse_preorder(root):
    result = []

    def visit(node):
        if node is None:
            return
        result.append(node.value)
        visit(node.right)
        visit(node.left)

    visit(root)
    return result


def reverse_inorder(root):
    result = []

    def visit(node):
        if node is None:
            return
        visit(node.right)
        result.append(node.value)
        visit(node.left)

    visit(root)
    return result


def reverse_postorder(root):
    result = []

    def visit(node):
        if node is None:
            return
        visit(node.right)
        visit(node.left)
        result.append(node.value)

    visit(root)
    return result


def is_valid_bst(root):
    def check(node, lower, upper):
        if node is None:
            return True
        if lower is not None and node.value <= lower:
            return False
        if upper is not None and node.value >= upper:
            return False
        return (check(node.left, lower, node.value)
                and check(node.right, node.value, upper))

    return check(root, None, None)


def is_balanced(root):
    def height(node):
        if node is None:
            return 0
        left_height = height(node.left)
        if left_height == -1:
            return -1
        right_height = height(node.right)
        if right_height == -1:
            return -1
        if abs(left_height - right_height) > 1:
            return -1
        return 1 + max(left_height, right_height)

    return height(root) != -1
