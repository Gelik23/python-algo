"""
Задача 2. Permutations

Как решаем
-------------
Строим перестановку по одному числу. Выбираем первое число, затем второе,
пока не заполним все места. Готовый вариант копируем в результат.
После этого отменяем последний выбор и пробуем другой. Это поиск с возвратом.

В counts храним, сколько раз еще можно взять каждое число.
Для [2, -1, 2] получаем {2: 2, -1: 1}. Выбирая 2, уменьшаем его счетчик,
но вторую такую же ветку на том же уровне не создаем. Поэтому одинаковые
перестановки не повторяются. Работаем с целыми числами, включая отрицательные.

В backtrack(path) сначала проверяем, готова ли перестановка.
Если нет, перебираем числа, которые еще можно взять.
Уменьшаем счетчик, добавляем число и рекурсивно строим продолжения.
После возврата убираем число через pop и восстанавливаем счетчик.
Так следующая ветка начинается с того же состояния, что предыдущая.

Через path.copy() сохраняем отдельный список, потому что path дальше меняется.
backtrack возвращает число найденных продолжений. Так в выводе видно,
сколько перестановок получилось из каждой ветки.
Сам permutations возвращает список всех найденных перестановок.

Почему это работает
-----------------------
На каждом месте пробуем все значения, которые еще доступны. Поэтому любая
перестановка получится в одной из веток. Счетчики не дают взять число
больше раз, чем оно встречается во входе. Для одинаковых чисел создаем
одну ветку, поэтому повторных ответов нет. Входной список не меняем.
Для пустого массива получаем одну пустую перестановку, то есть [[]].

Визуализация. повтор, отрицательное число и ноль
------------------------------------------------
Берем [2, -1, 2, 0]. В начале counts = {2: 2, -1: 1, 0: 1}.
Одинаковые двойки не считаем разными значениями. Поэтому результатов
будет 4! / 2! = 12, а не 24. Ноль тоже участвует в перестановках.

Дерево первых двух выборов. Справа указано, сколько ответов дает ветка.
[] -> 12
├── [2] -> 6
│   ├── [2, 2] -> 2
│   ├── [2, -1] -> 2
│   └── [2, 0] -> 2
├── [-1] -> 3
│   ├── [-1, 2] -> 2
│   └── [-1, 0] -> 1
└── [0] -> 3
    ├── [0, 2] -> 2
    └── [0, -1] -> 1

Пошагово пройдем начало ветки с двумя двойками.
Счетчики в таблице идут в порядке (2, -1, 0).
Шаг | Действие             | path          | Осталось
1   | начало               | []            | (2, 1, 1)
2   | выбираем 2           | [2]           | (1, 1, 1)
3   | выбираем еще 2       | [2, 2]        | (0, 1, 1)
4   | выбираем -1          | [2, 2, -1]    | (0, 0, 1)
5   | выбираем 0           | [2, 2, -1, 0] | (0, 0, 0)
6   | сохраняем ответ      | [2, 2, -1, 0] | (0, 0, 0)
7   | отменяем 0           | [2, 2, -1]    | (0, 0, 1)
8   | отменяем -1          | [2, 2]        | (0, 1, 1)
9   | выбираем 0           | [2, 2, 0]     | (0, 1, 0)
10  | выбираем -1          | [2, 2, 0, -1] | (0, 0, 0)
11  | сохраняем ответ      | [2, 2, 0, -1] | (0, 0, 0)

После завершения обеих перестановок возвращаемся к [2], восстанавливаем
счетчики до (1, 1, 1) и выбираем -1 вместо второй двойки.
Для [-1, 0] продолжение только одно, потому что остались две одинаковые
двойки. Поэтому количество ответов у веток отличается.

Результаты в порядке обхода
[2, 2, -1, 0]
[2, 2, 0, -1]
[2, -1, 2, 0]
[2, -1, 0, 2]
[2, 0, 2, -1]
[2, 0, -1, 2]
[-1, 2, 2, 0]
[-1, 2, 0, 2]
[-1, 0, 2, 2]
[0, 2, 2, -1]
[0, 2, -1, 2]
[0, -1, 2, 2]

Начало вывода до завершения ветки [2, 2]
-> backtrack([])
  -> backtrack([2])
    -> backtrack([2, 2])
      -> backtrack([2, 2, -1])
        -> backtrack([2, 2, -1, 0])
        <- backtrack([2, 2, -1, 0]) = 1
      <- backtrack([2, 2, -1]) = 1
      -> backtrack([2, 2, 0])
        -> backtrack([2, 2, 0, -1])
        <- backtrack([2, 2, 0, -1]) = 1
      <- backtrack([2, 2, 0]) = 1
    <- backtrack([2, 2]) = 2
Дальше идут ветки [2, -1], [2, 0], затем [-1] и [0].
В конце получаем строку <- backtrack([]) = 12.
Чтобы увидеть весь вывод, вызываем permutations с trace=True.

Сложность
----------
Без трассировки для n разных чисел время O(n * n!). Есть n! ответов,
каждый длины n. Словарь работает в среднем за O(1) на обращение.
Дополнительная память O(n) нужна для пути, счетчиков и стека рекурсии.
Сам результат занимает O(n * n!) памяти в худшем случае.
Если есть повторы, ответов n! / (c1! * c2! * ...). Здесь ci показывает,
сколько раз встречается каждое число.
На каждом вызове трассировка создает строки и печатает их, поэтому
для больших входов ее можно выключить через trace=False.
"""

from homework_5.tracer.solution import tracer


def permutations(nums, trace=False):
    result = []
    counts = {}

    for value in nums:
        counts[value] = counts.get(value, 0) + 1

    def backtrack(path):
        if len(path) == len(nums):
            result.append(path.copy())
            return 1

        count = 0

        for value in counts:
            if counts[value] == 0:
                continue

            counts[value] -= 1
            path.append(value)

            count += backtrack(path)

            path.pop()
            counts[value] += 1

        return count

    if trace:
        backtrack = tracer(backtrack)

    backtrack([])
    return result
