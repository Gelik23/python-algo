"""
Задача 1. Tracer

Как решаем
-------------
Декоратор получает функцию и добавляет к ней вывод. Сначала печатаем вход,
потом вызываем саму функцию и печатаем ее ответ. Вычисления внутри функции
от этого не меняются.

В depth храним глубину рекурсии. Перед вызовом увеличиваем ее на 1,
после вызова уменьшаем. Каждый следующий уровень получает еще два пробела.
Вход и возврат одного вызова печатаем с одинаковым отступом.

*args собирает позиционные аргументы, а **kwargs собирает именованные.
nonlocal позволяет менять depth из внешней функции, не создавая новую
переменную с таким именем. repr показывает значения аргументов и результата.
В finally уменьшаем глубину даже после ошибки, чтобы следующий запуск
не начинался с неправильным отступом. Ошибку передаем дальше через raise.

Почему это работает
-----------------------
При входе добавляем к глубине 1, при выходе вычитаем 1. Пока внутренний
вызов не закончился, внешний ждет в стеке. Поэтому по счетчику видно,
сколько вызовов сейчас вложено друг в друга.
У каждой функции свой счетчик. Здесь отслеживаем рекурсивные вызовы одной
функции. Общий стек нескольких разных функций этот вариант не показывает.

Визуализация. сумма чисел во вложенном списке
---------------------------------------------
Возьмем вложенный список [4, [-2, [], [7, -3]], 0].
Здесь есть разная глубина вложенности, отрицательные значения, пустой
список и ноль. nested_sum принимает целое число или список таких элементов.
У числа сразу возвращаем его значение, у списка складываем ответы детей.
Пустой список возвращает 0, не делая дочерних вызовов.

Дерево вызовов
[4, [-2, [], [7, -3]], 0]
├── 4 -> 4
├── [-2, [], [7, -3]] -> 2
│   ├── -2 -> -2
│   ├── [] -> 0
│   └── [7, -3] -> 4
│       ├── 7 -> 7
│       └── -3 -> -3
└── 0 -> 0

Вывод декоратора
-> nested_sum([4, [-2, [], [7, -3]], 0])
  -> nested_sum(4)
  <- nested_sum(4) = 4
  -> nested_sum([-2, [], [7, -3]])
    -> nested_sum(-2)
    <- nested_sum(-2) = -2
    -> nested_sum([])
    <- nested_sum([]) = 0
    -> nested_sum([7, -3])
      -> nested_sum(7)
      <- nested_sum(7) = 7
      -> nested_sum(-3)
      <- nested_sum(-3) = -3
    <- nested_sum([7, -3]) = 4
  <- nested_sum([-2, [], [7, -3]]) = 2
  -> nested_sum(0)
  <- nested_sum(0) = 0
<- nested_sum([4, [-2, [], [7, -3]], 0]) = 6

Сначала заканчивается вложенная ветка. Получаем 7 + (-3) = 4,
затем -2 + 0 + 4 = 2. Только после ее возврата начинается последний
вызов для 0. В корне получаем 4 + 2 + 0 = 6.
И [] и число 0 возвращают 0. Но для списка перебираем элементы, которых
здесь нет, а для числа сразу возвращаем его значение. Обе ветки завершаются.

Сложность
----------
Декоратор не меняет число рекурсивных вызовов. Без форматирования и вывода
добавляет O(1) работы на каждый вызов. Реальная стоимость зависит от длины
строк аргументов, результатов и отступов. Печать не занимает O(1).
При h активных вызовах строки отступов занимают суммарно O(h²) символов.
Строки аргументов и результатов добавляют память согласно своим размерам.
В примере nested_sum без трассировки посещает каждый элемент и список
один раз. Это O(m) времени, где m обозначает число узлов дерева вложенности.
Стек занимает O(h), где h обозначает максимальную глубину. При трассировке
добавляются строки со всеми вложенными списками и отступами; на цепочке
вложенных списков их суммарный размер может быть квадратичным по m.
Вход предполагается конечным, без циклических ссылок.
"""


def tracer(func):
    depth = 0

    def wrapper(*args, **kwargs):
        nonlocal depth

        parts = [repr(arg) for arg in args]
        for key, value in kwargs.items():
            parts.append(f"{key}={value!r}")

        call = f"{func.__name__}({', '.join(parts)})"
        indent = "  " * depth

        print(f"{indent}-> {call}")
        depth += 1

        try:
            result = func(*args, **kwargs)
        except Exception as error:
            print(f"{indent}!! {call}: {error}")
            raise
        else:
            print(f"{indent}<- {call} = {result!r}")
            return result
        finally:
            depth -= 1

    wrapper.__name__ = func.__name__
    return wrapper
