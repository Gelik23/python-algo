"""
Идея алгоритма
---------------
Два слова являются анаграммами, если после сортировки их букв
получается одна и та же строка.

Например:
    "eat" -> "aet"
    "tea" -> "aet"
    "ate" -> "aet"

Поэтому используем хеш-таблицу (dict):
    key   -> отсортированное слово
    value -> список исходных слов с таким ключом

Алгоритм:
1. Создаём пустой словарь groups.
2. Для каждого слова:
   - сортируем его символы
   - объединяем их обратно в строку — это ключ
   - добавляем исходное слово в список по этому ключу
3. Возвращаем все группы из словаря.

Почему решение корректно
------------------------
Если два слова являются анаграммами, у них одинаковый набор букв
с одинаковым количеством повторений, поэтому после сортировки
получается одинаковый ключ.

И наоборот: если отсортированные строки одинаковы, значит исходные
слова состоят из одинаковых букв с одинаковыми частотами, то есть
являются анаграммами.

Оценка сложности
----------------
Пусть:
    n — количество слов,
    k — максимальная длина слова.

Сортировка одного слова занимает O(k log k).
Для n слов:
    время: O(n * k log k)

Дополнительная память:
    O(n * k)

Она нужна для хранения ключей и сгруппированных слов.

Визуализация на сложном нетривиальном примере
-------------------------------------------------
Вход:
    [
        "listen", "silent", "enlist",
        "aabbc", "abcab",
        "stone", "tones", "notes",
        "bcaab",
        "evil", "vile", "veil"
    ]

Здесь специально есть:
- несколько групп по три слова;
- слова разной длины;
- группа с повторяющимися буквами ("aabbc", "abcab", "bcaab");
- разные группы, которые нельзя смешивать между собой.

Пошаговая работа:

Шаг | слово   | ключ после сортировки | groups после добавления
----|---------|------------------------|---------------------------------------------
1   | listen  | eilnst                 | {"eilnst": ["listen"]}
2   | silent  | eilnst                 | {"eilnst": ["listen", "silent"]}
3   | enlist  | eilnst                 | {"eilnst": ["listen", "silent", "enlist"]}
4   | aabbc   | aabbc                  | + {"aabbc": ["aabbc"]}
5   | abcab   | aabbc                  | "aabbc": ["aabbc", "abcab"]
6   | stone   | enost                  | + {"enost": ["stone"]}
7   | tones   | enost                  | "enost": ["stone", "tones"]
8   | notes   | enost                  | "enost": ["stone", "tones", "notes"]
9   | bcaab   | aabbc                  | "aabbc": ["aabbc", "abcab", "bcaab"]
10  | evil    | eilv                   | + {"eilv": ["evil"]}
11  | vile    | eilv                   | "eilv": ["evil", "vile"]
12  | veil    | eilv                   | "eilv": ["evil", "vile", "veil"]

Финальное состояние хеш-таблицы:
    {
        "eilnst": ["listen", "silent", "enlist"],
        "aabbc": ["aabbc", "abcab", "bcaab"],
        "enost": ["stone", "tones", "notes"],
        "eilv": ["evil", "vile", "veil"]
    }

Результат:
    [
        ["listen", "silent", "enlist"],
        ["aabbc", "abcab", "bcaab"],
        ["stone", "tones", "notes"],
        ["evil", "vile", "veil"]
    ]

Особенно важен шаг с "bcaab":
    sorted("bcaab") -> "aabbc"

Он попадает в ту же группу, что "aabbc" и "abcab",
хотя буквы повторяются и стоят в совершенно другом порядке.
Это показывает, что ключ учитывает еще количество повторений каждой буквы.

Альтернативный способ
----------------------
Если условие гарантирует, что слова состоят только из 26 строчных
английских букв, вместо сортировки можно считать количество каждой
буквы и использовать кортеж из 26 счётчиков как ключ.

Тогда построение ключа для одного слова занимает O(k), а вся задача —
O(n * k). В этом решении используется более простой и универсальный
вариант через сортировку.
"""


def group_anagrams(words: list[str]) -> list[list[str]]:
    groups: dict[str, list[str]] = {}

    for word in words:
        key = "".join(sorted(word))

        if key not in groups:
            groups[key] = []

        groups[key].append(word)

    return list(groups.values())
