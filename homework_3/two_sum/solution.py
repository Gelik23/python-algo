"""
Two Sum

Идея алгоритма
---------------
Проходим массив один раз и храним в словаре ``seen`` уже просмотренные
числа и их индексы в формате ``число -> индекс``.

Для текущего числа ``num`` вычисляем дополнение:

    complement = k - num

Если ``complement`` уже есть в ``seen``, значит найдено два элемента,
сумма которых равна ``k``. Возвращаем индекс найденного дополнения и
индекс текущего элемента.

Если дополнения нет, сохраняем текущий элемент в ``seen`` и продолжаем
обход.

Важно: сначала проверяем наличие дополнения и только потом добавляем
текущий элемент в словарь. Благодаря этому один и тот же элемент массива
не может быть использован дважды.

Оценка сложности
----------------
Пусть n — длина массива.

Время: O(n) в среднем.
Массив обходится один раз. Проверка наличия ключа и добавление элемента в
хеш-таблицу выполняются в среднем за O(1).

Дополнительная память: O(n).
В худшем случае в словаре ``seen`` может храниться до n элементов.

Визуализация на нетривиальном примере
-------------------------------------

nums = [4, -7, 12, 3, -2, 9], k = 5

Изначально:
    seen = {}

Шаг 1:
    i = 0, num = 4
    complement = 5 - 4 = 1

    1 нет в seen

    добавляем 4 -> 0
    seen = {4: 0}


Шаг 2:
    i = 1, num = -7
    complement = 5 - (-7) = 12

    12 нет в seen

    добавляем -7 -> 1
    seen = {4: 0, -7: 1}


Шаг 3:
    i = 2, num = 12
    complement = 5 - 12 = -7

    -7 уже есть в seen и имеет индекс 1

    возвращаем [1, 2]


Проверка:
    nums[1] + nums[2] = -7 + 12 = 5
"""


def two_sum(nums: list[int], k: int) -> list[int] | None:

    seen: dict[int, int] = {}

    for i, num in enumerate(nums):
        complement = k - num

        if complement in seen:
            return [seen[complement], i]

        seen[num] = i

    return None
